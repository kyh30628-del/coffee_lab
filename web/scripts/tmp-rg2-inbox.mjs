import { neon } from '@neondatabase/serverless';
import fs from 'fs';
const env = fs.readFileSync('.env.local','utf8');
const url = env.match(/DATABASE_URL="?([^"\n]+)"?/)[1];
const sql = neon(url);
const inbox = await sql`SELECT id,from_team,type,topic,stage,status,created_at FROM coordination WHERE to_team ILIKE '%룰갭%' AND status IN ('open','in_progress') ORDER BY created_at`;
console.log("INBOX to 룰갭발굴팀:", inbox.length);
inbox.forEach(r=>console.log(r.id, r.from_team, r.type, r.topic, r.stage, r.status, r.created_at));
const mine = await sql`SELECT id,from_team,to_team,type,topic,stage,status,created_at FROM coordination WHERE from_team ILIKE '%룰갭%' AND status IN ('open','in_progress') ORDER BY created_at`;
console.log("\nMY open coordination (from 룰갭발굴팀):", mine.length);
mine.forEach(r=>console.log(r.id, "->", r.to_team, r.type, r.topic, r.stage, r.status, r.created_at));
