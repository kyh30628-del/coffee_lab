//
// 왜 필요한가 — **구조적 한계 때문이다.**
//   우리가 가진 리뷰 텍스트는 블로그 원문이 아니라 네이버 검색 API가 주는 **요약 스니펫(평균 153자)**이다.
//   협찬 공시("소정의 원고료를 지원받아 작성")는 관행상 글 **끝**에 붙는데, 스니펫엔 앞부분만 들어온다.
//   → 공시어 기반 규칙(reviewQuality의 AD_DISCLAIM 등)은 원천적으로 못 보는 사각이 있다.
//   실측(2026-08-16): 노출 인용문 77,861건 중 '협찬/체험단' 표면 매칭은 0.1%뿐인데,
//   아래 템플릿 신호로는 1,193건(1.5%·1,142곳)이 잡힌다. 사장님 체감이 맞았다.
//
// 무엇을 잡나 — 협찬 글은 공시를 지워도 **업체 정보 카드**라는 지문을 남긴다.
//   실제 노출 예: "⭐️매주 일요일 휴무⭐️ 영업시간 ⏰월~금 07:30~18:00 무선인터넷, 주차불가 ☎️0507-…"
//   맛도 분위기도 없고 영업시간·주차·전화번호만 나열된다.
//
// ⚠️ 설계 원칙(오탐 안전): 이 판정은 **노출 순서만** 바꾼다. 삭제·비공개·등급강등 없음.
//   "주차 정보도 알려주는 착한 후기"가 오탐으로 걸려도 사라지지 않고 뒤로 갈 뿐이다.
//   단독 신호로는 절대 판정하지 않는다 — 정보 신호 2개 이상 **그리고** 개인 감상이 하나도 없을 때만.

/** 업체 정보 카드 신호(개별로는 무해 — 조합이 지문이다). */
const INFO_SIGNALS: RegExp[] = [
  /영업\s?시간/,                              // 영업시간 나열
  /주차\s?(가능|불가|안내|장)/,                // 주차 안내
  /[★⭐]/,                                    // 별점 표기(체험단 정형)
  /\d{2,3}-\d{3,4}-\d{4}|\*{3}-/,             // 전화번호(마스킹형 포함)
  /위치 및 이용|이용 안내|메뉴판|가격표/,        // 안내 블록
  // ── 2026-08-17 보강: 아래 4종이 없어 실측 7,826건(표시 인용문의 10.1%)을 통째로 놓치고 있었다.
  //    놓친 실례: "카페루엘 서울 마포구 삼개로3길 9 1-2층 10:30-20:00 매주 토/일 정기휴무"
  //    → '영업시간'이라는 낱말이 없으면 시간표가 대놓고 있어도 신호 0이었다.
  /\d{1,2}\s?:\s?\d{2}\s?[-~]\s?\d{1,2}\s?:\s?\d{2}/,   // 숫자형 영업시간(08:00-22:00, 08 : 00 ~ 22 : 00)
  /[가-힣]{2,}(로|길)\s?\d+(\s?[-–]\s?\d+)?/,            // 도로명 주소(삼개로3길 9)
  /정기\s?휴무|휴무일|매주\s?[월화수목금토일]|브레이크\s?타임|라스트\s?오더/, // 휴무·운영 안내
  /오는\s?길|찾아가는|위치\s?:|주소\s?:/,                 // 길안내 블록
];

/** 사람이 실제로 다녀와야 나오는 말 — 하나라도 있으면 템플릿으로 보지 않는다(오탐 방지의 핵심). */
// 2026-08-17: 감상어 사전이 좁아 진짜 후기가 템플릿으로 몰릴 위험이 있어 함께 넓혔다.
//   신호를 늘릴 때 면제어도 같이 늘려야 오탐이 안 는다(한쪽만 늘리면 그물이 사람을 잡는다).
//   실측 검증(2026-08-17, 표본 6,000건): 신호만 넓혔더니 "새로 생긴 카페가 있어서 가보았어요",
//   "요즘 유행한다는 버터떡 먹어봤어요" 같은 **진짜 후기가 걸렸다.** 1인칭 경험 어미를 면제어에 추가해 바로잡았다.
//   3차 보강(전수 감사): 표시 인용문 77,866건 **전수**에 돌려보니 판정 12,387건 중 130건이
//   "오늘로써 3번째 방문이었어요"·"인테리어도 예뻐서 방문하였습니다"처럼 **주소·영업시간을 같이 적은 진짜 후기**였다.
//   → 정보 나열이 있어도 **1인칭 서술 어미**가 보이면 사람이 쓴 글로 본다(정보카드는 명사 나열이라 이런 어미가 거의 없다).
const PERSONAL_IMPRESSION =
  /맛있|맛은|맛이|좋았|괜찮|아쉬|추천해|재방문|또 가|또 오|분위기가|친절|편안|시켰|먹었|마셨|앉아|들렀|다녀왔|방문했|주문했|즐기|만족|취향|생각나|기분|느낌이|봤|보았|왔어|왔습니|갔다|들러|먹어|마셔|시켜|앉았|구경|골라|했어요|하였|했습니다|였어요|이었어요|였습니다|더라구|더라고|생각보다|개인적으로|처음엔|궁금했|인상적|재밌|예뻐|이뻐|친구랑|아이가/;

/** 해시태그 3개 이상 = 검색 노출용 키워드 폭탄(대행 글의 흔한 마감). */
function hashtagCount(t: string): number {
  return (t.match(/#/g) || []).length;
}

/**
 * 문장 종결어미 개수 — **사전이 아닌 구조로** 사람 글을 알아보는 장치(2026-08-17).
 *
 * 왜 이 방식인가: 감상어 사전을 넓히는 방식은 수렴하지 않았다. 탐침을 바꿀 때마다
 * 새 오탐("오늘 제가 방문한 곳은", "우리가 갔을 때")이 나와 단어를 계속 덧붙이게 된다 — 반응적 땜질이다.
 * 반면 **정보 카드는 명사·기호 나열이라 종결어미가 구조적으로 거의 없고**, 사람이 쓴 글은 반드시 있다.
 * 이건 어휘와 무관하므로 새로운 표현이 나와도 규칙을 고칠 필요가 없다.
 */
function sentenceEndings(t: string): number {
  return (t.match(/(요|다|죠|네|음|함|까)(?=[\s.!?,~…"')\]]|$)/g) || []).length;
}

/**
 * 광고 대행 템플릿 여부.
 * @returns true면 '후기'가 아니라 '업체 정보 카드'로 판단 → 노출 뒤로 민다.
 */
export function isAdTemplateQuote(quote?: string | null): boolean {
  const t = String(quote || "");
  if (t.length < 20) return false;                 // 너무 짧으면 판단 보류(무해 쪽으로)
  if (PERSONAL_IMPRESSION.test(t)) return false;   // 개인 감상이 있으면 진짜 후기로 존중
  if (sentenceEndings(t) >= 2) return false;       // 서술 문장이 둘 이상이면 사람 글(어휘 무관 구조 판정)
  let signals = INFO_SIGNALS.reduce((n, re) => n + (re.test(t) ? 1 : 0), 0);
  if (hashtagCount(t) >= 3) signals++;
  return signals >= 2;                             // 단독 신호 금지 — 2개 이상 조합만
}
