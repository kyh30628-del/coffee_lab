// 무엇을 잡나 — 협찬 글은 공시를 지워도 **업체 정보 카드**라는 지문을 남긴다.
//   실제 노출 예: "⭐️매주 일요일 휴무⭐️ 영업시간 ⏰월~금 07:30~18:00 무선인터넷, 주차불가 ☎️0507-…"
//   맛도 분위기도 없고 영업시간·주차·전화번호만 나열된다.
//
// ⚠️ 설계 원칙(오탐 안전): 이 판정은 **노출 순서만** 바꾼다. 삭제·비공개·등급강등 없음.
//   "주차 정보도 알려주는 착한 후기"가 오탐으로 걸려도 사라지지 않고 뒤로 갈 뿐이다.
//   단독 신호로는 절대 판정하지 않는다 — 정보 신호 2개 이상 **그리고** 개인 감상이 하나도 없을 때만.

/** 업체 정보 카드 신호(개별로는 무해 — 조합이 지문이다). */
const INFO_SIGNALS: RegExp[] = [
  /영업\s?시간/,                              // 영업시간 나열
  /주차\s?(가능|불가|안내)/,                   // 주차 안내
  /[★⭐]/,                                    // 별점 표기(체험단 정형)
  /\d{2,3}-\d{3,4}-\d{4}|\*{3}-/,             // 전화번호(마스킹형 포함)
  /위치 및 이용|이용 안내|메뉴판|가격표/,        // 안내 블록
];

/** 사람이 실제로 다녀와야 나오는 말 — 하나라도 있으면 템플릿으로 보지 않는다(오탐 방지의 핵심). */
const PERSONAL_IMPRESSION =
  /맛있|맛은|맛이|좋았|괜찮|아쉬|추천해|재방문|또 가|또 오|분위기가|친절|편안|시켰|먹었|마셨|앉아|들렀|다녀왔/;

/** 해시태그 3개 이상 = 검색 노출용 키워드 폭탄(대행 글의 흔한 마감). */
function hashtagCount(t: string): number {
  return (t.match(/#/g) || []).length;
}

/**
 * 광고 대행 템플릿 여부.
 * @returns true면 '후기'가 아니라 '업체 정보 카드'로 판단 → 노출 뒤로 민다.
 */
export function isAdTemplateQuote(quote?: string | null): boolean {
  const t = String(quote || "");
  if (t.length < 20) return false;                 // 너무 짧으면 판단 보류(무해 쪽으로)
  if (PERSONAL_IMPRESSION.test(t)) return false;   // 개인 감상이 있으면 진짜 후기로 존중
  let signals = INFO_SIGNALS.reduce((n, re) => n + (re.test(t) ? 1 : 0), 0);
  if (hashtagCount(t) >= 3) signals++;
  return signals >= 2;                             // 단독 신호 금지 — 2개 이상 조합만
}
