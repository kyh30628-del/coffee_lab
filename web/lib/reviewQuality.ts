  // 짧은 단일토큰(≤2자)뿐 아니라 '숫자만'인 단일토큰('102커피'→"102")도 약함 — 주소 번지('102호')·다른 업체에
  //   오매칭됨. → 전체 이름('102커피') 원문 일치만 인정해 차단.
  const weakWhitelist = onlyTok.length >= 1 && WEAK_IDENTITY_TOKEN.has(onlyTok); // #153 초약체 유일토큰
