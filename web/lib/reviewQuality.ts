  // (예: '롯데백화점'에서 '점'이 떨어져 '롯데백화'가 되면 venue 매칭을 빠져나가는 것 방지)
  // 공백뿐 아니라 한글↔영문/숫자 경계로도 분리 → '노원두물마루COFFEESNACK'처럼 붙은 이름에서
  //   한글 식별어('노원두물마루')를 분리(영문 접미사 통째로 토큰화돼 일치율 0 되는 오판 방지).
