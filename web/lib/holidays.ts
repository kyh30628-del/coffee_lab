/** 표가 덮는 마지막 연도 — 넘어가면 '모른다'고 말해야 한다(조용히 평일로 세지 않기 위해). */
export const HOLIDAY_TABLE_YEARS: readonly number[] = [2026];

export function isHoliday(day: string): boolean {
  return day in KR_HOLIDAYS;
}
export function holidayName(day: string): string | null {
  return KR_HOLIDAYS[day] ?? null;
}
/** 표가 그 해를 덮지 않으면 true — 화면·리포트에서 "공휴일 반영 안 됨"을 밝히는 용도. */
export function isOutsideTable(day: string): boolean {
  const y = Number(day.slice(0, 4));
  return Number.isFinite(y) && !HOLIDAY_TABLE_YEARS.includes(y);
}
/** 통계 분류: 공휴일 > 주말 > 평일. dow는 0=일 … 6=토(KST 기준). */
export function dayType(day: string, dow: number): "공휴일" | "주말" | "평일" {
  if (isHoliday(day)) return "공휴일";
  return dow === 0 || dow === 6 ? "주말" : "평일";
}
